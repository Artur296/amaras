const CART_STORAGE_KEY = 'amaras_cart_items';

function getCart() {
  try {
    const raw = localStorage.getItem(CART_STORAGE_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch (e) {
    return [];
  }
}

function saveCart(cart) {
  try {
    localStorage.setItem(CART_STORAGE_KEY, JSON.stringify(cart));
  } catch (e) {}
  updateCartBadges();
}

function updateCartBadges() {
  const cart = getCart();
  const totalCount = cart.reduce((acc, item) => acc + (item.quantity || 1), 0);
  document.querySelectorAll('.amaras-cart-badge').forEach(badge => {
    badge.textContent = totalCount;
    if (totalCount > 0) {
      badge.style.display = 'inline-flex';
    }
  });
}

function addToCart(item) {
  const cart = getCart();
  const existing = cart.find(i => i.id === item.id);
  if (existing) {
    existing.quantity = (existing.quantity || 1) + (item.quantity || 1);
  } else {
    cart.push({
      id: item.id || ('tour_' + Date.now()),
      title: item.title || 'Экскурсионный тур',
      price: item.price || 12000,
      image: item.image || 'assets/hero/tour-1-khorvirap.jpg',
      route: item.route || '',
      quantity: item.quantity || 1
    });
  }
  saveCart(cart);

  // Bump badges
  document.querySelectorAll('.amaras-cart-badge').forEach(badge => {
    badge.classList.remove('is-bumped');
    void badge.offsetWidth;
    badge.classList.add('is-bumped');
  });
}

function updateCartItemQty(id, delta) {
  let cart = getCart();
  const item = cart.find(i => i.id === id);
  if (item) {
    item.quantity = (item.quantity || 1) + delta;
    if (item.quantity <= 0) {
      cart = cart.filter(i => i.id !== id);
    }
  }
  saveCart(cart);
  renderCartPage();
}

function removeCartItem(id) {
  let cart = getCart();
  cart = cart.filter(i => i.id !== id);
  saveCart(cart);
  renderCartPage();
}

function clearCart() {
  saveCart([]);
  renderCartPage();
}

