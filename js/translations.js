// Mobile Navigation Functions
function toggleMobileDropdown(btn) {
  const dropdown = btn.closest('.amaras-mobile-dropdown');
  if (dropdown) dropdown.classList.toggle('is-open');
}

function toggleMobileNestedDropdown(btn) {
  const nested = btn.closest('.amaras-mobile-nested-dropdown');
  if (nested) nested.classList.toggle('is-open');
}

function toggleDesktopSubmenu(el, e) {
  if (e) e.stopPropagation();
  const wrapper = el.closest('.amaras-dropdown-subitem-wrapper');
  if (wrapper) wrapper.classList.toggle('is-open');
}

function toggleSearchBar() {
  const overlay = document.querySelector('.amaras-search-bar-overlay');
  if (overlay) {
    const isOpen = overlay.classList.toggle('is-open');
    if (isOpen) {
      const input = overlay.querySelector('.amaras-search-input');
      if (input) setTimeout(() => input.focus(), 120);
    }
  }
}

function toggleMobileNav() {
  const drawer = document.querySelector('.amaras-mobile-drawer');
  if (drawer) drawer.classList.toggle('is-open');
}

function toggleMobileLangMenu(e) {
  if (e) {
    e.stopPropagation();
    e.preventDefault();
  }
  const menu = document.getElementById('mobileLangMenu');
  const trigger = document.getElementById('mobileLangTrigger');
  if (!menu || !trigger) return;
  const isOpen = menu.classList.contains('is-open');
  if (isOpen) {
    closeMobileLangMenu();
  } else {
    menu.classList.add('is-open');
    trigger.classList.add('is-open');
    trigger.setAttribute('aria-expanded', 'true');
  }
}

function closeMobileLangMenu() {
  const menu = document.getElementById('mobileLangMenu');
  const trigger = document.getElementById('mobileLangTrigger');
  if (menu) menu.classList.remove('is-open');
  if (trigger) {
    trigger.classList.remove('is-open');
    trigger.setAttribute('aria-expanded', 'false');
  }
}

function selectMobileLang(lang) {
  setLang(lang);
  closeMobileLangMenu();
}

// Universal setLang Function
function setLang(lang) {
  if (!AMARAS_I18N[lang]) return;
  window.currentLang = lang;
  document.body.setAttribute('data-lang', lang);
  document.documentElement.setAttribute('lang', lang === 'HY' ? 'hy' : (lang === 'ENG' ? 'en' : 'ru'));

  const shortLabel = LANG_SHORT_LABELS[lang] || lang;

  // Update mobile trigger and drawer labels
  const mobileCurrent = document.getElementById('mobileLangCurrent');
  if (mobileCurrent) mobileCurrent.textContent = shortLabel;
  const mobileFlag = document.getElementById('mobileLangFlag');
  if (mobileFlag && LANG_FLAGS[lang]) mobileFlag.innerHTML = LANG_FLAGS[lang];
  const drawerCurrent = document.getElementById('drawerLangCurrent');
  if (drawerCurrent) drawerCurrent.textContent = shortLabel;

  // Update desktop switcher active buttons
  document.querySelectorAll('.amaras-lang-btn').forEach(btn => {
    const bLang = btn.getAttribute('data-lang') || btn.innerText.trim();
    btn.classList.toggle('is-active', bLang === lang || bLang === shortLabel);
  });

  // Update mobile popover menu active item
  document.querySelectorAll('.amaras-mobile-lang-item').forEach(item => {
    item.classList.toggle('is-active', item.getAttribute('data-lang-choice') === lang);
  });

  // Update drawer segmented tab
  document.querySelectorAll('.amaras-drawer-lang-tab').forEach(btn => {
    const bLang = btn.getAttribute('data-lang') || btn.innerText.trim();
    btn.classList.toggle('is-active', bLang === lang || bLang === shortLabel);
  });

  const dict = AMARAS_I18N[lang];

  // Update all elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // Update inputs with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  // Update <title> if head title has data-i18n
  const headTitle = document.querySelector('title[data-i18n]');
  if (headTitle && dict[headTitle.getAttribute('data-i18n')]) {
    document.title = dict[headTitle.getAttribute('data-i18n')];
  }

  // Update aria-labels
  const searchBtn = document.querySelector('.amaras-search-btn');
  if (searchBtn && dict.search_label) {
    searchBtn.setAttribute('aria-label', dict.search_label);
    searchBtn.setAttribute('title', dict.search_label);
  }
  const cartBtn = document.querySelector('.amaras-cart-btn');
  if (cartBtn && dict.cart_label) {
    cartBtn.setAttribute('aria-label', dict.cart_label);
    cartBtn.setAttribute('title', dict.cart_label);
  }

  // Update search placeholder
  document.querySelectorAll('.amaras-search-input').forEach(input => {
    if (dict.search_placeholder) input.setAttribute('placeholder', dict.search_placeholder);
  });

  // Update cart buttons text if not in added state
  document.querySelectorAll('.amaras-btn-cart:not(.is-added) .amaras-btn-cart-text').forEach(t => {
    t.textContent = dict.btn_add_to_cart || 'В корзину';
  });

  // Recalculate tour constructor if active
  if (typeof window.recalcTourBuilder === 'function') {
    window.recalcTourBuilder();
  }

  try {
    localStorage.setItem('amaras_preferred_lang', lang);
  } catch (e) { }
}

// Global Click Handlers
document.addEventListener('click', (e) => {
  // Popover close on outside click
  const wrapper = document.getElementById('mobileLangWrapper');
  if (wrapper && !wrapper.contains(e.target)) {
    closeMobileLangMenu();
  }
  if (!e.target.closest('.amaras-dropdown-subitem-wrapper')) {
    document.querySelectorAll('.amaras-dropdown-subitem-wrapper.is-open').forEach(w => w.classList.remove('is-open'));
  }

  // Universal Add to Cart Handler
  const btn = e.target.closest('.amaras-btn-cart');
  if (btn) {
    e.preventDefault();
    e.stopPropagation();

    const currentLang = window.currentLang || localStorage.getItem('amaras_preferred_lang') || 'RU';
    const dict = AMARAS_I18N[currentLang] || AMARAS_I18N.RU;

    // Increment badges
    const badges = document.querySelectorAll('.amaras-cart-badge');
    badges.forEach(badge => {
      let count = parseInt(badge.textContent, 10) || 0;
      count += 1;
      badge.textContent = count;
      badge.classList.remove('is-bumped');
      void badge.offsetWidth;
      badge.classList.add('is-bumped');
    });

    // Button visual feedback
    const textSpan = btn.querySelector('.amaras-btn-cart-text') || btn.querySelector('span');
    const originalText = textSpan ? textSpan.textContent : (dict.btn_add_to_cart || 'В корзину');
    btn.classList.add('is-added');
    if (textSpan) textSpan.textContent = dict.btn_added_to_cart || 'Добавлено ✓';

    setTimeout(() => {
      btn.classList.remove('is-added');
      if (textSpan) {
        const freshDict = AMARAS_I18N[window.currentLang || 'RU'] || AMARAS_I18N.RU;
        textSpan.textContent = freshDict.btn_add_to_cart || 'В корзину';
      }
    }, 1600);
  }
});

document.addEventListener('keydown', (e) => {
  if (e.key === 'Escape') {
    closeMobileLangMenu();
    const overlay = document.querySelector('.amaras-search-bar-overlay');
    if (overlay && overlay.classList.contains('is-open')) toggleSearchBar();
  }
});

// Initialize language & navigation on DOMContentLoaded
document.addEventListener('DOMContentLoaded', () => {
  // Dropdown pin
  document.querySelectorAll('.amaras-nav-dropdown').forEach(dropdown => {
    const link = dropdown.querySelector('.amaras-nav-link');
    if (link) {
      link.addEventListener('click', (e) => {
        e.preventDefault();
        const isOpen = dropdown.classList.contains('is-open');
        document.querySelectorAll('.amaras-nav-dropdown').forEach(d => d.classList.remove('is-open'));
        if (!isOpen) dropdown.classList.add('is-open');
      });
    }
  });

  // Close pinned dropdowns when clicking outside
  document.addEventListener('click', (e) => {
    if (!e.target.closest('.amaras-nav-dropdown')) {
      document.querySelectorAll('.amaras-nav-dropdown').forEach(d => d.classList.remove('is-open'));
    }
  });

  document.querySelectorAll('.amaras-dropdown-item').forEach(item => {
    item.addEventListener('click', () => {
      document.querySelectorAll('.amaras-nav-dropdown').forEach(d => d.classList.remove('is-open'));
    });
  });

  document.querySelectorAll('.amaras-mobile-drawer-links a').forEach(a => {
    a.addEventListener('click', () => {
      const drawer = document.querySelector('.amaras-mobile-drawer');
      if (drawer) drawer.classList.remove('is-open');
    });
  });

  try {
    const saved = localStorage.getItem('amaras_preferred_lang');
    if (saved && AMARAS_I18N[saved]) {
      setLang(saved);
    } else {
      setLang('RU');
    }
  } catch (e) {
    setLang('RU');
  }
});
